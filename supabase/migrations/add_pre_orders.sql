-- Re-runnable: every statement is idempotent.

-- ─────────────────────────────────────────────────────────────────────
-- 1. pre_orders
-- ─────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS pre_orders (
  id                    UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  -- Public tracking code, e.g. "PR-2026-0042". Generated by the action
  -- layer; we just enforce uniqueness here.
  tracking_code         TEXT UNIQUE,

  -- Customer (can be a walk-in — no client_id required)
  customer_id           UUID REFERENCES clients(id) ON DELETE SET NULL,
  customer_name         TEXT NOT NULL,
  customer_whatsapp     TEXT NOT NULL,

  -- Product + variant
  product_id            UUID NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  variant_id            UUID REFERENCES product_variants(id) ON DELETE SET NULL,

  -- Pricing snapshot (captured at order time, not derived)
  unit_cost             NUMERIC(14, 2) NOT NULL CHECK (unit_cost >= 0),
  shipping_cost         NUMERIC(14, 2) NOT NULL CHECK (shipping_cost >= 0),
  unit_price            NUMERIC(14, 2) NOT NULL CHECK (unit_price > 0),
  deposit_amount        NUMERIC(14, 2) NOT NULL CHECK (deposit_amount > 0),
  balance_due           NUMERIC(14, 2) NOT NULL CHECK (balance_due >= 0),

  -- Shipping
  shipping_mode         TEXT NOT NULL CHECK (shipping_mode IN ('sea', 'air')),

  -- Funnel: 'pos' (walk-in) or 'catalog' (online)
  source                TEXT NOT NULL CHECK (source IN ('pos', 'catalog')),

  -- Status (transitions are validated by the action layer; CHECK
  -- just protects against bad writes)
  status                TEXT NOT NULL DEFAULT 'pending'
                          CHECK (status IN (
                            'pending', 'deposit_paid', 'arrived',
                            'completed', 'cancelled', 'refunded'
                          )),

  -- Delivery target (computed from shipping_mode at order time)
  expected_delivery_date DATE NOT NULL,

  -- Optional customer-facing notes
  notes                 TEXT,

  -- Denormalised status timestamps (the events table holds the
  -- full timeline; these are for fast filtering and reporting)
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deposit_paid_at       TIMESTAMPTZ,
  arrived_at            TIMESTAMPTZ,
  completed_at          TIMESTAMPTZ,
  cancelled_at          TIMESTAMPTZ,
  refunded_at           TIMESTAMPTZ,

  -- Set when the pre-order converts to a sale
  sale_id               UUID REFERENCES sales(id) ON DELETE SET NULL
);

-- Indexes
-- 1) Default admin list: by status + created_at desc
CREATE INDEX IF NOT EXISTS idx_pre_orders_status_created
  ON pre_orders (status, created_at DESC);

-- 2) Customer lookup by WhatsApp (catalog self-serve + tracking)
CREATE INDEX IF NOT EXISTS idx_pre_orders_whatsapp
  ON pre_orders (customer_whatsapp);

-- 3) Tracking code (already UNIQUE but explicit index for clarity)
CREATE INDEX IF NOT EXISTS idx_pre_orders_tracking_code
  ON pre_orders (tracking_code);

-- 4) Active pre-orders for a product (used by the catalog to show
-- "N people waiting" hint on the product page)
CREATE INDEX IF NOT EXISTS idx_pre_orders_product_active
  ON pre_orders (product_id, status)
  WHERE status IN ('pending', 'deposit_paid', 'arrived');

-- updated_at trigger
CREATE OR REPLACE FUNCTION pre_orders_touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pre_orders_touch_updated_at ON pre_orders;
CREATE TRIGGER trg_pre_orders_touch_updated_at
  BEFORE UPDATE ON pre_orders
  FOR EACH ROW
  EXECUTE FUNCTION pre_orders_touch_updated_at();

-- RLS
ALTER TABLE pre_orders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can manage pre_orders"
  ON pre_orders;
CREATE POLICY "Authenticated users can manage pre_orders"
  ON pre_orders
  FOR ALL
  TO authenticated
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');

