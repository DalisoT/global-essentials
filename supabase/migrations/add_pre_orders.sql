-- Design:
--   - Pricing snapshot (unit_cost, shipping_cost, unit_price, deposit_amount,
--     balance_due) is captured at pre-order time, not derived. This means
--     we can re-issue a receipt months later and the numbers still match.
--   - tracking_code is a short, public-friendly code (e.g. PR-2026-0042).
--     Generated by the action layer, not here — we just store and index it.
--   - source ('pos' | 'catalog') lets us report on which funnel is working.
--   - shipping_mode ('sea' | 'air') controls expected delivery date and
--     shipping cost formula. Sea = +50 days, air = +14 days.
--   - All status transitions are timestamped individually so the event
--     timeline shows what happened when. The pre_order_events table holds
--     the full story; status fields on the row are just denormalised
--     for fast filtering.
