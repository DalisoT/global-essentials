-- 2. pre_order_events
-- ─────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS pre_order_events (
  id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  pre_order_id    UUID NOT NULL REFERENCES pre_orders(id) ON DELETE CASCADE,
  -- 'created' | 'deposit_paid' | 'notified' | 'arrived' |
  -- 'balance_paid' | 'completed' | 'cancelled' | 'refunded' |
  -- 'status_changed' | 'message_queued' | 'message_sent'
  event_type      TEXT NOT NULL,
  -- Free-form JSON. Always at least { from, to } on status_changed;
  -- { amount, method } on payment events.
  event_data      JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pre_order_events_order
  ON pre_order_events (pre_order_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_pre_order_events_type
  ON pre_order_events (event_type, created_at DESC);

-- RLS
ALTER TABLE pre_order_events ENABLE ROW LEVEL SECURITY;

