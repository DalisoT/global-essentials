COMMENT ON TABLE forecasts IS
  'Predictive AI / forecasting cache. One row per (kind, target_id, horizon_days). The nightly Vercel Cron (Phase 7.8) regenerates expired rows.';

COMMENT ON COLUMN forecasts.kind IS
  'demand = per-product sales forecast; cashflow = business-wide inflows/outflows; default_risk = per-client probability of missing a payment.';

COMMENT ON COLUMN forecasts.target_id IS
  'NULL for business-wide forecasts. For demand: products.id. For default_risk: clients.id.';

COMMENT ON COLUMN forecasts.payload IS
  'Forecast data. Shape depends on kind. See lib/actions/forecast.ts for the TypeScript types.';
